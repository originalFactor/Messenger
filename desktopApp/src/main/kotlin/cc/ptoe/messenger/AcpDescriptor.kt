package cc.ptoe.messenger

import cc.ptoe.messenger.core.HttpServerHandle
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.StandardCopyOption
import java.nio.file.attribute.AclEntry
import java.nio.file.attribute.AclEntryPermission
import java.nio.file.attribute.AclEntryType
import java.nio.file.attribute.AclFileAttributeView
import java.nio.file.attribute.PosixFilePermission
import java.nio.file.attribute.PosixFilePermissions

internal fun writeAcpDescriptor(path: Path, server: HttpServerHandle) {
    val posix = Files.getFileStore(path.parent).supportsFileAttributeView("posix")
    val ownerPermissions = setOf(PosixFilePermission.OWNER_READ, PosixFilePermission.OWNER_WRITE)
    val temp = if (posix) {
        Files.createTempFile(path.parent, ".acp-", ".tmp", PosixFilePermissions.asFileAttribute(ownerPermissions))
    } else {
        Files.createTempFile(path.parent, ".acp-", ".tmp")
    }
    try {
        if (!posix) {
            val acl = requireNotNull(Files.getFileAttributeView(temp, AclFileAttributeView::class.java))
            acl.acl = listOf(AclEntry.newBuilder()
                .setType(AclEntryType.ALLOW)
                .setPrincipal(acl.owner)
                .setPermissions(AclEntryPermission.entries.toSet())
                .build())
        }
        // Both values are generated by Core from ASCII socket and UUID components.
        Files.writeString(temp, """{"address":"${server.localAddr()}","token":"${server.token()}"}""")
        Files.move(temp, path, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING)
    } finally {
        Files.deleteIfExists(temp)
    }
}

internal fun removeAcpDescriptor(path: Path, token: String) {
    if (Files.exists(path) && Files.readString(path).contains(token)) {
        Files.deleteIfExists(path)
    }
}
